// ponytail: o texto do React é encurtado no lugar e ganha irmãos | limite: se o React remover só esse nó de texto, o ponto e o resto sobram até recarregar | gatilho: nome duplicado ou ponto solto na barra lateral | dono: resper@ness.com.br
;(function () {
  if (typeof document === 'undefined') return
  var NOME = 'ness.work'
  var extras = new WeakMap()
  var FORA = 'textarea, input, pre, code, [contenteditable="true"]'
  function pintar(raiz) {
    var w = document.createTreeWalker(raiz, NodeFilter.SHOW_TEXT)
    var achados = []
    for (var n = w.nextNode(); n; n = w.nextNode()) {
      var pai = n.parentElement
      if (pai && n.nodeValue.indexOf(NOME) >= 0 && n.nodeValue.trim() === NOME && !pai.closest(FORA)) achados.push(n)
    }
    achados.forEach(function (n) {
      var velhos = extras.get(n)
      if (velhos) velhos.forEach(function (x) { if (x.parentNode) x.parentNode.removeChild(x) })
      var v = n.nodeValue
      var i = v.indexOf(NOME)
      var ponto = document.createElement('span')
      ponto.textContent = '.'
      ponto.style.color = '#00ADE8'
      var resto = document.createTextNode('work' + v.slice(i + NOME.length))
      n.nodeValue = v.slice(0, i) + 'ness'
      n.parentNode.insertBefore(resto, n.nextSibling)
      n.parentNode.insertBefore(ponto, resto)
      extras.set(n, [ponto, resto])
    })
  }
  function iniciar() {
    pintar(document.body)
    new MutationObserver(function () { pintar(document.body) })
      .observe(document.body, { childList: true, subtree: true, characterData: true })
  }
  if (document.body) iniciar()
  else document.addEventListener('DOMContentLoaded', iniciar)
})()
